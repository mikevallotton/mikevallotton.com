export function sourcesFor(noteNames) {
  const ids = [...new Set(noteNames.flatMap((name) => evidenceNotes[name].sourceIds))];
  return ids.map((id) => evidenceSources[id]);
}

export function mergeSources(...lists) {
  const byUrl = new Map();
  lists.flat().forEach((source) => {
    if (!byUrl.has(source.href)) byUrl.set(source.href, source);
  });
  return [...byUrl.values()];
}
